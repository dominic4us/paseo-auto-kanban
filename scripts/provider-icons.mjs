#!/usr/bin/env node
// REQ-73: turns the provider marks in assets/provider-icons/*.svg into the PNG data URIs of
// client/provider-icons.ts. Plugin client code cannot load react-native-svg (the host resolves only react,
// react-native, zod and the plugin SDK), and a native Image does not draw SVG, so the marks ship as
// black-on-transparent PNGs that the card tints with `tintColor`, as Paseo tints them with `color`.
// usage: . spike/plugin-hello/scripts/chromium-env.sh; node scripts/provider-icons.mjs <path to the playwright package>
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
if (!process.argv[2]) { console.error('usage: node scripts/provider-icons.mjs <path to the playwright package>'); process.exit(2); }
const pw = createRequire(import.meta.url)(process.argv[2]);
const SIZE = 48;
const icons = ['claude', 'codex', 'gemini'];
const browser = await pw.chromium.launch({ headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE }, deviceScaleFactor: 1 });
const out = {};
for (const name of icons) {
  const svg = readFileSync(join(root, 'assets/provider-icons', name + '.svg'), 'utf8').replace(/<!--[\s\S]*?-->\s*/, '')
    .replace('width="24" height="24"', `width="${SIZE}" height="${SIZE}"`);
  await page.setContent(`<html><body style="margin:0;background:transparent">${svg}</body></html>`);
  out[name] = (await page.locator('svg').screenshot({ omitBackground: true, type: 'png' })).toString('base64');
}
await browser.close();
const lines = icons.map(name => `  ${name}: 'data:image/png;base64,${out[name]}',`);
writeFileSync(join(root, 'client/provider-icons.ts'), `// Generated by scripts/provider-icons.mjs from assets/provider-icons/*.svg — do not edit by hand.
// The marks are Paseo's own provider icons, copied unchanged (shape, proportions, orientation) from
// https://github.com/getpaseo/paseo (Apache-2.0): packages/app/src/components/icons/claude-icon.tsx,
// codex-icon.tsx and packages/app/src/assets/acp-provider-icons/gemini.svg. Each mark is a trademark of its
// owner and is shown only to say which provider an agent runs on; see NOTICE.
/** ${SIZE}px black-on-transparent PNGs, tinted by the caller like Paseo's single-colour \`color\` prop. */
export const PROVIDER_ICON_PNG = {
${lines.join('\n')}
} as const;
`);
console.log('wrote client/provider-icons.ts', Object.fromEntries(icons.map(n => [n, out[n].length])));
