import { readFile, writeFile } from 'node:fs/promises';
// REQ-48: server/version.ts is a compile-time constant, generated fresh on every build. The plugin
// bundle runs as an eval'd child process with no path to its own install directory (no
// cwd override, no import.meta.url), so package.json cannot be read at runtime; this keeps the two
// version strings in sync the same way `npm run build` already keeps dist/cli/main.js in sync.
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const release = await readFile(new URL('../release.json', import.meta.url), 'utf8')
  .then(JSON.parse).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
if (release && (release.version !== pkg.version || typeof release.release !== 'string' || !release.release.trim()))
  throw new Error('release.json must match package.json and contain a release identifier');
const content = `// Generated by scripts/sync-server-version.mjs from package.json. Do not edit by hand.\n` +
  `export const PACKAGE_VERSION = ${JSON.stringify(pkg.version)};\n` +
  `export const BUILD_RELEASE: string | undefined = ${release ? JSON.stringify(release.release) : "undefined"};\n`;
const target = new URL('../server/version.ts', import.meta.url);
const current = await readFile(target, 'utf8').catch(() => '');
if (current !== content) await writeFile(target, content);
