/** How a pick names a built-in workflow: the id alone, so a later version of the same id is what the lane shows. */
export const BUILTIN_ID = /^[a-z][a-z0-9-]{0,39}$/;
export function builtinWorkflow(id: string | null | undefined): BuiltinWorkflow | undefined {
  return id ? BUILTIN_WORKFLOWS.find(t => t.id === id) : undefined;
}
/** The steps a list row previews: the first row's, in column order. */
export function builtinPreview(template: BuiltinWorkflow, locale: WorkflowLocale): { label: string; decision: boolean }[] {
  return template.stages.filter(s => s.row === 0).sort((a, b) => a.col - b.col).map(s => ({ label: s[locale], decision: s.shape === 'diamond' }));
}
/** The current-format definition of a built-in workflow, in one language (the screen's). */
export function builtinDefinition(template: BuiltinWorkflow, locale: WorkflowLocale): WorkflowDefinition {
  const name = template.name[locale];
  return {
    format: WORKFLOW_FORMAT, name: locale === 'ko' ? name + ' — 기본 틀' : name + ' — built-in',
    note: locale === 'ko' ? `칸반에 내장된 기본 틀 '${name}'(${template.id} v${template.version}) — 단계와 선만 있고 문서를 읽는 규칙은 없다.`
      : `The built-in workflow "${name}" (${template.id} v${template.version}) — steps and lines only, no rules for reading documents.`,
    releaseKey: 'semver',
    stages: template.stages.map(s => ({ id: s.id, label: s[locale], shape: s.shape, row: s.row, col: s.col, ...(s.person ? { person: true } : {}) })),
    edges: template.edges.map(e => ({ from: e.from, to: e.to, ...(e.when ? { when: e.when } : {}), ...(e.back ? { back: true } : {}),
      ...(e.optional ? { optional: true } : {}), ...(e[locale] ? { label: e[locale] } : {}) })),
    sources: [],
  };
}
