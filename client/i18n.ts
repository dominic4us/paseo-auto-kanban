/**
 * REQ-82: a stage name with the Korean "to" particle — "완료로", "진행으로", "검토로". 로 follows a vowel or ㄹ, 으로
 * any other final consonant; a name that does not end in a Hangul syllable ("Review") gets "(으)로".
 */
export function withRo(name: string): string {
  const text = name.trim(), last = text.codePointAt(text.length - 1) ?? 0;
  if (last < 0xac00 || last > 0xd7a3) return name + '(으)로';
  const final = (last - 0xac00) % 28;
  return name + (final === 0 || final === 8 ? '로' : '으로');
}

/** Only the built-in English stage display is renamed; stored templates are never rewritten. */
export function displayStageNames<T extends { template: { id: string; version: number; stages: { stageId: string; name: string }[] }; stages?: { stageId: string; name: string }[] }>(value: T, locale: Locale): T {
  if (locale !== 'en' || value.template.id !== 'basic' || value.template.version !== 1) return value;
  const rename = <S extends { stageId: string; name: string }>(stage: S): S => stage.stageId === 'todo' ? { ...stage, name: 'To Do' } : stage;
  return { ...value, template: { ...value.template, stages: value.template.stages.map(rename) },
    ...(value.stages ? { stages: value.stages.map(rename) } : {}) };
}
